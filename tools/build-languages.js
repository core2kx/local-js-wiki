#!/usr/bin/env node
'use strict';
/* Developer tool (Node; not needed to use the wiki).
   Turns each languages/<code>.json into js/lang/<code>.js, the script that index.html loads, because a
   page opened by double-clicking cannot read JSON files from its own folder.

     node tools/build-languages.js            write the js/lang files
     node tools/build-languages.js --check    only check that they are up to date (the tests use this)

   Edit languages/*.json, never js/lang/*.js. To add a built-in language: copy languages/en.json to
   languages/<code>.json, translate the values, set "language", run this tool, and add
   <script defer src="js/lang/<code>.js"></script> to index.html (after en.js). */
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const sourceDir = path.join(root, 'languages');
const targetDir = path.join(root, 'js', 'lang');

// The script text for one language file; only English carries the translator notes.
function scriptFor(code, file) {
  const content = {language: file.language, strings: file.strings};
  if (code === 'en' && file.notes) content.notes = file.notes;
  return '/* Generated by tools/build-languages.js from languages/' + code + '.json. Edit the JSON file, not this one. */\n' +
    'globalThis.LocalWiki.i18n.register(' + JSON.stringify(content, null, 1) + ');\n';
}
function build({check = false} = {}) {
  const problems = [], written = [];
  fs.mkdirSync(targetDir, {recursive: true});
  for (const name of fs.readdirSync(sourceDir).filter(n => n.endsWith('.json')).sort()) {
    const code = name.slice(0, -5);
    const file = JSON.parse(fs.readFileSync(path.join(sourceDir, name), 'utf8'));
    const target = path.join(targetDir, code + '.js');
    const wanted = scriptFor(code, file);
    const actual = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (actual === wanted) continue;
    if (check) problems.push(`js/lang/${code}.js is ${actual === null ? 'missing' : 'out of date'}`);
    else { fs.writeFileSync(target, wanted); written.push(code); }
  }
  return {problems, written};
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const {problems, written} = build({check});
  if (problems.length) { console.error(problems.join('\n') + '\nRun: node tools/build-languages.js'); process.exit(1); }
  console.log(check ? 'Language scripts are up to date.' : (written.length ? 'Wrote: ' + written.join(', ') : 'Nothing to do.'));
}
module.exports = {build, scriptFor};
